function updateLayoutMode() {
  const isHome = currentMode === "home";
  const isImage = currentMode === "image";
  const shouldHideIndexOnMobile = isMobileView() && !isHome;
  const shouldHideIndexOnDesktop = isImage;

  indexPanel.classList.toggle(
    "is-hidden",
    shouldHideIndexOnMobile || shouldHideIndexOnDesktop
  );

  indexPanel.classList.toggle("is-home-full", isHome);

  detailPanel.classList.toggle("is-full", isImage);
  detailPanel.classList.toggle("is-hidden", isHome);
  detailPanel.classList.toggle("has-border", !isHome && !isImage);

  mainElement?.classList.toggle("is-image-mode", isImage);

  if (currentMode !== "project") {
    detailPanel.classList.remove("no-media");
  }
}

function wrapByLang(text, lang) {
  return `<span lang="${lang}">${text}</span>`;
}

function escapeHtml(text = "") {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function replaceLinks(text = "") {
  return text.replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, (_, label, url) => {
    return `<a class="detail-link" href="${url}" target="_blank" rel="noopener noreferrer">${escapeHtml(label)}</a>`;
  });
}

function normalizeText(text = "") {
  return text
    .replace(/&ndash;/g, "–")
    .replace(/\[\^\d+\]/g, "")
    .trim();
}

function parseDescription(text = "") {
  const cleaned = normalizeText(text);

  if (!cleaned) return "";

  const blocks = cleaned.split(/\n\s*\n/);

  /* 실제 텍스트 기준 언어 판별 */
  function detectLang(text = "") {
    return /[가-힣]/.test(text) ? "ko" : "en";
  }

  return blocks.map((block) => {
    const trimmed = block.trim();

    /* audio */
    if (
      trimmed.startsWith("<audio") &&
      trimmed.endsWith("</audio>")
    ) {
      return `<div class="detail-audio">${trimmed}</div>`;
    }

    /* 인용문 */
    if (trimmed.startsWith(">")) {
      const quoteLines = trimmed
        .split("\n")
        .map((line) => line.replace(/^>\s?/, "").trim())
        .filter(Boolean);

      const sourceLine = quoteLines.find((line) =>
        line.startsWith("—")
      );

      const quoteOnlyLines = quoteLines.filter(
        (line) => !line.startsWith("—")
      );

      /* 출처 앞 원래 — 제거 */
const sourceText = sourceLine
  ? sourceLine.replace(/^—\s*/, "")
  : "";

      const quoteText = quoteOnlyLines.join(" ");

      /* 인용 내용 기준으로 언어 판별 */
      const quoteLang = detectLang(quoteText);

      const isListQuote = quoteOnlyLines.length > 1;

      /* 리스트형 인용문 */
      if (isListQuote) {
        return `
          <blockquote
            class="detail-quote detail-quote-list"
            lang="${quoteLang}"
          >
            <ul>
              ${quoteOnlyLines
                .map((line) => {
                  const lineLang = detectLang(line);

                  return `
                    <li lang="${lineLang}">
                      ${replaceLinks(escapeHtml(line))}
                    </li>
                  `;
                })
                .join("")}
            </ul>

            ${
              sourceText
                ? `
                  <div class="detail-quote-source">
                    ${replaceLinks(escapeHtml(sourceText))}
                  </div>
                `
                : ""
            }
          </blockquote>
        `;
      }

      /* 일반 인용문 */
      return `
        <blockquote
          class="detail-quote"
          lang="${quoteLang}"
        >
          ${replaceLinks(
            escapeHtml(quoteOnlyLines.join("\n"))
          )}

          ${
            sourceText
              ? `
                <div class="detail-quote-source">
                  ${replaceLinks(escapeHtml(sourceText))}
                </div>
              `
              : ""
          }
        </blockquote>
      `;
    }

    /* 일반 문단 */
    const textLang = detectLang(trimmed);

    return `
      <p
        class="detail-paragraph"
        lang="${textLang}"
      >
        ${replaceLinks(escapeHtml(trimmed))}
      </p>
    `;
  }).join("");
}

function isNotYetProject(project) {
  return (
    project.description?.ko?.trim().toLowerCase() === "not yet." &&
    project.description?.en?.trim().toLowerCase() === "not yet."
  );
}

function getProjectMedia(project) {
  if (project.images && project.images.length > 0) return project.images;
  if (project.image && project.image.src) return [project.image];
  return [];
}

function renderProjects() {
  projectList.innerHTML = "";

  projectList.classList.remove("is-inline");
  projectList.classList.add("is-stair");

  projects.forEach((project, index) => {
    const isActive = currentMode === "project" && currentProjectId === project.id;
    const isInactive = currentMode === "project" && currentProjectId !== project.id;
    const isDisabled = isNotYetProject(project);

    const item = document.createElement("span");
    item.className = `project-list-item${isActive ? " is-active" : ""}${isInactive ? " is-inactive" : ""}${isDisabled ? " is-disabled" : ""}`;

    /*if (shouldStair) {
      const randomColumn = Math.floor(Math.random() * 50);
      item.style.marginLeft = `${randomColumn}em`;
    } else {
      item.style.marginLeft = "";
    }*/


    item.dataset.id = project.id;

    if (isDisabled) {
      item.setAttribute("aria-disabled", "true");
    } else {
      item.setAttribute("role", "button");
      item.setAttribute("tabindex", "0");
    }

    item.innerHTML = `
      <span class="project-list-title">${wrapByLang(project.title[currentLang], currentLang)}</span>
    `;

    const openProject = () => {
      currentProjectId = project.id;
      currentMode = "project";
      renderProjects();
      renderDetail();
    };

    if (!isDisabled) {
      item.addEventListener("click", openProject);

      item.addEventListener("keydown", (event) => {
        if (event.key === "Enter" || event.key === " ") {
          event.preventDefault();
          openProject();
        }
      });
    }

    projectList.appendChild(item);
  });
}

function renderMedia(media) {
  if (!media.length) {
    return "";
  }

  return `
    <div class="detail-media">
      ${media.map((item) => {
    if (item.type === "video") {
      return `
<video
  class="detail-image detail-video"
  src="${item.src}"
  autoplay
  muted
  loop
  playsinline
></video>
          `;
    }

    return `
          <img
            class="detail-image"
            src="${item.src}"
            alt="${item.alt?.[currentLang] || ""}"
          />
        `;
  }).join("")}
    </div>
  `;
}

function renderProjectMeta(project) {
  const meta = project.meta?.[currentLang];

  if (!meta) {
    return "";
  }

  const values = [
    meta.year,
    meta.production,
    meta.size,
    meta.printing,
    meta.paper,
    meta.color,
    meta.pages,
    meta.time,
    meta.binding,
  ].filter(Boolean);

  return `
    <aside class="detail-meta">
      ${values.map((value) => `
        <div class="detail-meta-item">
          <div class="detail-meta-value">
            ${wrapByLang(value, currentLang)}
          </div>
        </div>
      `).join("")}
    </aside>
  `;
}

function renderProjectDetail(project, imageOnly = false) {
  const media = getProjectMedia(project);
  const textHtml = parseDescription(project.description[currentLang]);

  return `
    <article class="detail-entry">
      ${renderMedia(media)}
      ${imageOnly ? "" : `
        <div class="detail-lower">
          <div class="detail-text" lang="${currentLang}">${textHtml}</div>
          ${renderProjectMeta(project)}
        </div>
      `}
    </article>
  `;
}

function renderHomeDetail() {
  return `<article class="detail-entry"></article>`;
}

function renderImageArchive() {
  const allImages = projects.flatMap((project) => getProjectMedia(project));

  if (!allImages.length) {
    return `<div class="detail-empty">${wrapByLang("Image not available", "en")}</div>`;
  }

  return `
    <div class="image-archive">
      ${allImages.map((image) => `
<img
  class="image-archive-item ${image.size === "large" ? "is-large" : ""}"
  src="${image.src}"
  alt="${image.alt?.[currentLang] || ""}"
/>
      `).join("")}
    </div>
  `;
}

function renderDetail() {
  detailContent.classList.remove("is-image-mode");

  if (currentMode === "image") {
    detailContent.classList.add("is-image-mode");
    detailContent.innerHTML = renderImageArchive();
    updateLayoutMode();
    return;
  }

  if (!currentProjectId) {
    detailContent.innerHTML = renderHomeDetail();
    updateLayoutMode();
    return;
  }

  const project = projects.find((item) => item.id === currentProjectId);
  if (!project) {
    detailContent.innerHTML = renderHomeDetail();
    updateLayoutMode();
    return;
  }

  const media = getProjectMedia(project);
  detailPanel.classList.toggle("no-media", media.length === 0);

  detailContent.innerHTML = renderProjectDetail(project, false);
  updateLayoutMode();
  bindMediaDragScroll();
}

